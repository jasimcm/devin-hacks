"""80mm-wide receipt PDF with ReportLab.

Item names are printed in English only: ReportLab cannot shape Malayalam text correctly.
"""
from datetime import datetime
from io import BytesIO

import qrcode
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.lib.utils import ImageReader
from reportlab.pdfbase.pdfmetrics import stringWidth
from reportlab.pdfgen import canvas

import store

WIDTH = 80 * mm
MARGIN = 4 * mm
ROW = 5 * mm
UNIT_SHORT = {"kg": "kg", "litre": "L", "piece": "pc", "packet": "pkt"}

# Column x positions: "#" and "Item" are left-aligned, the rest right-aligned.
COL_NO = MARGIN
COL_ITEM = MARGIN + 5 * mm
COL_QTY = 46 * mm
COL_RATE = 60 * mm
COL_AMOUNT = WIDTH - MARGIN


def format_qty(qty, unit):
    text = f"{qty:g}"
    return f"{text} {UNIT_SHORT.get(unit, unit)}"


def money(value):
    return f"{value:,.2f}"


def fit(text, font, size, max_width):
    """Cut text with '..' so it fits in the column."""
    if stringWidth(text, font, size) <= max_width:
        return text
    while text and stringWidth(text + "..", font, size) > max_width:
        text = text[:-1]
    return text + ".."


def qr_image(data):
    buffer = BytesIO()
    qrcode.make(data, border=1).save(buffer, format="PNG")
    buffer.seek(0)
    return ImageReader(buffer)


def build_pdf(bill):
    """The 80mm-wide receipt, for thermal printers and digital copies (PDF, WhatsApp)."""
    height = (98 * mm) + len(bill["items"]) * ROW
    buffer = BytesIO()
    pdf = canvas.Canvas(buffer, pagesize=(WIDTH, height))
    pdf.setTitle(f"Easy Bill {bill['bill_id']}")
    _draw_receipt(pdf, bill, height)
    pdf.showPage()
    pdf.save()
    return buffer.getvalue()


def build_a4_pdf(bill):
    """The same receipt at native 80mm size, centred at the top of an A4 page. Sent with
    -o media=A4 and no fit-to-page, so CUPS can't scale it up and the QR stays scannable."""
    receipt_height = (98 * mm) + len(bill["items"]) * ROW
    buffer = BytesIO()
    pdf = canvas.Canvas(buffer, pagesize=A4)
    pdf.setTitle(f"Easy Bill {bill['bill_id']}")
    pdf.saveState()
    pdf.translate((A4[0] - WIDTH) / 2, A4[1] - receipt_height - 10 * mm)  # centred, 10mm from top
    _draw_receipt(pdf, bill, receipt_height)
    pdf.restoreState()
    pdf.showPage()
    pdf.save()
    return buffer.getvalue()


def _draw_receipt(pdf, bill, height):
    """Draw the receipt block on `pdf`; `height` is the block's height in points."""
    items = bill["items"]
    center = WIDTH / 2
    y = height - MARGIN - 4 * mm

    def line(at):
        pdf.setLineWidth(0.5)
        pdf.setDash(1, 1.5)
        pdf.line(MARGIN, at, WIDTH - MARGIN, at)
        pdf.setDash()

    # Shop header
    pdf.setFont("Helvetica-Bold", 13)
    pdf.drawCentredString(center, y, store.SHOP_NAME)
    y -= 4.5 * mm
    pdf.setFont("Helvetica", 8)
    pdf.drawCentredString(center, y, store.SHOP_ADDRESS)
    y -= 3.8 * mm
    pdf.drawCentredString(center, y, f"Phone: {store.SHOP_PHONE}")
    y -= 3 * mm
    line(y)

    # Bill id and date
    created = datetime.fromisoformat(bill["created_at"])
    y -= 4.5 * mm
    pdf.setFont("Helvetica-Bold", 9)
    pdf.drawString(MARGIN, y, f"Bill: {bill['bill_id']}")
    pdf.setFont("Helvetica", 8)
    pdf.drawRightString(WIDTH - MARGIN, y, created.strftime("%d-%m-%Y  %I:%M %p"))
    y -= 3 * mm
    line(y)

    # Table header
    y -= 4.5 * mm
    pdf.setFont("Helvetica-Bold", 8)
    pdf.drawString(COL_NO, y, "#")
    pdf.drawString(COL_ITEM, y, "Item")
    pdf.drawRightString(COL_QTY, y, "Qty")
    pdf.drawRightString(COL_RATE, y, "Rate")
    pdf.drawRightString(COL_AMOUNT, y, "Amount")
    y -= 2 * mm
    line(y)

    # Rows
    pdf.setFont("Helvetica", 8)
    item_width = COL_QTY - COL_ITEM - 10 * mm
    for number, item in enumerate(items, start=1):
        y -= ROW
        pdf.drawString(COL_NO, y, str(number))
        pdf.drawString(COL_ITEM, y, fit(item["name_en"], "Helvetica", 8, item_width))
        pdf.drawRightString(COL_QTY, y, format_qty(item["qty"], item["unit"]))
        pdf.drawRightString(COL_RATE, y, money(item["price"]))
        pdf.drawRightString(COL_AMOUNT, y, money(item["line_total"]))
    y -= 2.5 * mm
    line(y)

    # Grand total
    y -= 6 * mm
    pdf.setFont("Helvetica-Bold", 12)
    pdf.drawString(MARGIN, y, "TOTAL")
    pdf.drawRightString(WIDTH - MARGIN, y, f"Rs. {money(bill['total'])}")
    y -= 5 * mm
    pdf.setFont("Helvetica", 8)
    pdf.drawCentredString(center, y, f"Paid via UPI  ({store.UPI_VPA})")

    # UPI QR code
    qr_size = 30 * mm
    y -= qr_size + 2 * mm
    pdf.drawImage(qr_image(store.upi_link(bill)), center - qr_size / 2, y, qr_size, qr_size)
    y -= 3.5 * mm
    pdf.setFont("Helvetica", 7)
    pdf.drawCentredString(center, y, "Scan to pay with any UPI app")

    # Footer
    y -= 3 * mm
    line(y)
    y -= 4 * mm
    pdf.setFont("Helvetica-Oblique", 7)
    pdf.drawCentredString(center, y, "Thank you! Visit again.  -  Generated by Easy Bill")


def build_summary_pdf(summary):
    """Day-end report PDF (store.day_summary()): totals and per-item sales, no QR."""
    items = summary["items"]
    height = (62 * mm) + len(items) * ROW
    buffer = BytesIO()
    pdf = canvas.Canvas(buffer, pagesize=(WIDTH, height))
    pdf.setTitle(f"{store.SHOP_NAME} day report {summary['date']}")
    center = WIDTH / 2
    y = height - MARGIN - 4 * mm

    def line(at):
        pdf.setLineWidth(0.5)
        pdf.setDash(1, 1.5)
        pdf.line(MARGIN, at, WIDTH - MARGIN, at)
        pdf.setDash()

    # Shop header
    pdf.setFont("Helvetica-Bold", 13)
    pdf.drawCentredString(center, y, store.SHOP_NAME)
    y -= 4.5 * mm
    pdf.setFont("Helvetica", 8)
    pdf.drawCentredString(center, y, store.SHOP_ADDRESS)
    y -= 3.8 * mm
    pdf.drawCentredString(center, y, f"Phone: {store.SHOP_PHONE}")
    y -= 3 * mm
    line(y)

    # Report title and counts
    day = datetime.fromisoformat(summary["date"])
    y -= 4.5 * mm
    pdf.setFont("Helvetica-Bold", 9)
    pdf.drawString(MARGIN, y, f"Day report: {day.strftime('%d %b %Y')}")
    pdf.setFont("Helvetica", 8)
    pdf.drawRightString(WIDTH - MARGIN, y, datetime.now().strftime("%I:%M %p"))
    y -= 4 * mm
    pdf.drawString(MARGIN, y, f"Bills: {summary['bill_count']}")
    pdf.drawRightString(WIDTH - MARGIN, y, f"Sent to customers: {summary['delivered']}")
    y -= 3 * mm
    line(y)

    # Table header
    y -= 4.5 * mm
    pdf.setFont("Helvetica-Bold", 8)
    pdf.drawString(COL_NO, y, "#")
    pdf.drawString(COL_ITEM, y, "Item")
    pdf.drawRightString(COL_RATE, y, "Qty")
    pdf.drawRightString(COL_AMOUNT, y, "Amount")
    y -= 2 * mm
    line(y)

    # Rows
    pdf.setFont("Helvetica", 8)
    item_width = COL_RATE - COL_ITEM - 8 * mm
    for number, item in enumerate(items, start=1):
        y -= ROW
        pdf.drawString(COL_NO, y, str(number))
        pdf.drawString(COL_ITEM, y, fit(item["name_en"], "Helvetica", 8, item_width))
        pdf.drawRightString(COL_RATE, y, format_qty(item["qty"], item["unit"]))
        pdf.drawRightString(COL_AMOUNT, y, money(item["revenue"]))
    y -= 2.5 * mm
    line(y)

    # Grand total
    y -= 6 * mm
    pdf.setFont("Helvetica-Bold", 12)
    pdf.drawString(MARGIN, y, "TOTAL")
    pdf.drawRightString(WIDTH - MARGIN, y, f"Rs. {money(summary['total'])}")

    # Footer
    y -= 4 * mm
    line(y)
    y -= 4 * mm
    pdf.setFont("Helvetica-Oblique", 7)
    pdf.drawCentredString(center, y, "Day summary  -  Generated by Easy Bill")

    pdf.showPage()
    pdf.save()
    return buffer.getvalue()
